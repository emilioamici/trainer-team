// E2E: timer allenamento, timer rapido e superset — modalità demo.
// Uso: npm run build && npx vite preview --port 4173 &  poi  node e2e/timer.cjs [cartella-screenshot]
const { chromium } = require('playwright')
const ok = (c, msg) => { console.log(c ? 'OK  ' : 'FAIL', msg); if (!c) process.exitCode = 1 }
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'it-IT', colorScheme: 'dark' })
  await ctx.addInitScript(() => { localStorage.setItem('trainer:gate', 'skip'); localStorage.setItem('trainer:tutorial_completed', 'true'); localStorage.setItem('trainer:role', 'coach') })
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(String(e)))
  await p.clock.install()
  await p.goto('http://localhost:4173/'); await p.waitForSelector('text=Oggi')

  // ---- timer rapido ----
  await p.getByRole('button', { name: 'Timer rapido' }).click()
  await p.getByRole('button', { name: "20''", exact: true }).first().click()
  await p.getByRole('button', { name: 'Nessuno', exact: true }).click()
  await p.getByRole('button', { name: 'Meno giri' }).click(); await p.getByRole('button', { name: 'Meno giri' }).click(); await p.getByRole('button', { name: 'Meno giri' }).click()
  ok((await p.getByTestId('quick-rounds').innerText()) === '2', 'timer rapido: 2 giri')
  await p.getByRole('button', { name: 'Avvia', exact: true }).click()
  await p.getByRole('button', { name: 'Inizia' }).click()
  ok((await p.getByTestId('timer-clock').innerText()) === '00:20', 'parte da 00:20')
  await p.clock.runFor(5000)
  ok((await p.getByTestId('timer-clock').innerText()) === '00:15', 'dopo 5 s mostra 00:15')
  await p.getByRole('button', { name: 'Pausa' }).click(); await p.clock.runFor(5000)
  ok((await p.getByTestId('timer-clock').innerText()) === '00:15', 'in pausa il tempo non scorre')
  await p.getByRole('button', { name: 'Riprendi' }).click(); await p.clock.runFor(16000)
  ok(await p.getByText('Serie 2 di 2').count() === 1, 'finito il primo giro passa al secondo')
  await p.clock.runFor(21000)
  ok(await p.getByText('Allenamento finito!').count() === 1, 'fine: schermata finale')
  await p.getByRole('button', { name: 'Chiudi', exact: true }).click(); await p.waitForTimeout(400)

  // ---- editor: superset ----
  await ctx.close()
  const ctx2 = await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'it-IT', colorScheme: 'dark' })
  await ctx2.addInitScript(() => { localStorage.setItem('trainer:gate', 'skip'); localStorage.setItem('trainer:tutorial_completed', 'true'); localStorage.setItem('trainer:role', 'coach') })
  const q = await ctx2.newPage(); q.on('pageerror', (e) => errs.push(String(e)))
  await q.goto('http://localhost:4173/'); await q.waitForSelector('text=Oggi')
  // dalla card di Oggi (demo) parte il timer guidato
  await q.getByRole('button', { name: 'Avvia timer' }).first().click()
  await q.getByRole('button', { name: 'Inizia' }).click()
  ok(await q.getByTestId('timer-label').count() === 1, 'Oggi: il tasto Timer avvia il timer guidato della sessione')
  await q.getByRole('button', { name: 'Chiudi timer' }).click(); await q.waitForTimeout(400)
  await q.getByRole('navigation').getByRole('button', { name: 'Piano', exact: true }).click(); await q.waitForSelector('[aria-label="Nuovo allenamento"]')
  await q.getByRole('button', { name: 'Nuovo allenamento' }).click(); await q.waitForTimeout(600)
  const dlg = q.getByRole('dialog')
  await dlg.getByRole('button', { name: 'Aggiungi superset' }).nth(1).click()
  const names = dlg.getByLabel('Nome esercizio')
  await names.nth(0).fill('Trazioni'); await names.nth(1).fill('Plank')
  ok(await dlg.getByRole('button', { name: 'Separa dal superset' }).count() === 1, 'editor: i due blocchi sono in superset')
  await dlg.getByRole('button', { name: 'Separa dal superset' }).click()
  ok(await dlg.getByRole('button', { name: 'Unisci al precedente in superset' }).count() === 1, 'editor: separabili')
  await dlg.getByRole('button', { name: 'Unisci al precedente in superset' }).click()
  await dlg.getByPlaceholder(/Es\.|titolo/i).first().fill('Forza test').catch(() => {})
  await names.nth(0).fill('Trazioni')
  const blocks = dlg.getByLabel('Note tecniche esercizio')
  ok(await blocks.count() >= 2, 'editor: due schede esercizio')
  await dlg.getByRole('button', { name: 'Salva', exact: true }).click(); await q.waitForTimeout(700)
  await q.getByText('Forza test').first().click(); await q.waitForTimeout(500)
  ok(await q.getByTestId('superset').count() === 1, 'dettaglio: i due esercizi sono raggruppati in un superset')
  await q.getByRole('button', { name: 'Avvia timer' }).click(); await q.getByRole('button', { name: 'Inizia' }).click()
  ok((await q.getByTestId('timer-label').innerText()) === 'Trazioni', 'timer guidato parte dal primo esercizio del superset')
  await q.getByRole('button', { name: 'Fatto', exact: true }).click()
  ok((await q.getByTestId('timer-label').innerText()) === 'Plank', 'poi alterna al secondo esercizio')
  if (process.argv[2]) await q.screenshot({ path: process.argv[2] + '/timer-editor.png' })
  ok(errs.length === 0, 'nessun errore in console ' + errs.join(' | '))
  await b.close()
})().catch((e) => { console.error('ERRORE', e); process.exit(1) })
